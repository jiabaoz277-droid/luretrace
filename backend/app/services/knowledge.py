def region_for_province(province: str | None) -> str:
    """省份 → 区域（北方/南方/全国）。未知时返回全国（不过滤）。"""
    if not province:
        return "全国"
    name = province
    for suffix in ["维吾尔自治区", "壮族自治区", "回族自治区", "自治区", "特别行政区", "省", "市"]:
        if name.endswith(suffix):
            name = name[: -len(suffix)]
            break
    if name in NORTH_PROVINCES:
        return "北方"
    return "南方"


def recommend_species(month: int, region: str = "全国") -> list[str]:
    """按月份 + 地域推荐候选目标鱼（地域特色鱼优先，最多 3 个）。"""
    regional = {
        "北方": ["狗鱼", "虹鳟"],  # 北方冷水特色
        "南方": ["罗非", "鳡鱼"],  # 南方热带/特有
    }.get(region, [])

    candidates: list[str] = ["翘嘴", "鳜鱼", "鲈鱼"]
    for months, species in SEASON_SPECIES.items():
        if month in months:
            candidates = species
            break

    result: list[str] = []
    for s in regional + candidates:
        if s not in result:
            result.append(s)
        if len(result) >= 3:
            break
    return result


def season_strategy(month: int) -> dict | None:
    """按月份返回四季作钓策略（含季节名）。"""
    for name, s in SEASON_STRATEGY.items():
        if month in s["months"]:
            return {"name": name, **s}
    return None


def normalize_species(name: str) -> str | None:
    return SPECIES_ALIASES.get(name.strip())


def get_species(name: str | None) -> dict | None:
    if not name:
        return None
    normalized = normalize_species(name)
    if normalized:
        return SPECIES_KNOWLEDGE.get(normalized)
    return None
